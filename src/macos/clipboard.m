// Clipboard history and pasting: what was copied (not what apps mark as
// secret: passwords), whether macOS lets this app read it, the app in
// front, and ⌘V sent to it (which needs Accessibility).

#import <AppKit/AppKit.h>
#import <ApplicationServices/ApplicationServices.h>

int64_t nf_pasteboard_count(void) {
    return NSPasteboard.generalPasteboard.changeCount;
}

// What macOS does when this app reads the clipboard by itself (macOS
// 15.4+): 0 never asked yet, 1 ask, 2 always allow, 3 always deny; -1:
// it doesn't ask (an older macOS).
int32_t nf_pasteboard_access(void) {
    if (@available(macOS 15.4, *)) {
        return (int32_t)NSPasteboard.generalPasteboard.accessBehavior;
    }
    return -1;
}

static NSString *json_string(id object) {
    NSData *data = [NSJSONSerialization dataWithJSONObject:object options:0 error:nil];
    return data ? [[NSString alloc] initWithData:data encoding:NSUTF8StringEncoding] : nil;
}

// What's on the clipboard, as JSON (malloc'd): {"count", "skip" (a
// password, or something only passing through), "files", "text", "image"
// (written as PNG to `image_out`, with "w" and "h"), "app", "app_path"
// (in front as it was copied)}. Reading it may make macOS ask, once.
char *nf_pasteboard_take(const char *image_out) {
    @autoreleasepool {
        NSPasteboard *pb = NSPasteboard.generalPasteboard;
        NSMutableDictionary *out = [NSMutableDictionary dictionary];
        out[@"count"] = @(pb.changeCount);
        NSRunningApplication *front = NSWorkspace.sharedWorkspace.frontmostApplication;
        if (front.localizedName) {
            out[@"app"] = front.localizedName;
        }
        if (front.bundleURL.path) {
            out[@"app_path"] = front.bundleURL.path;
        }
        // (The nspasteboard.org markers, and 1Password's own.)
        NSArray<NSString *> *types = pb.types ?: @[];
        NSSet *secret = [NSSet setWithArray:@[@"org.nspasteboard.ConcealedType", @"org.nspasteboard.TransientType", @"org.nspasteboard.AutoGeneratedType",
                                              @"com.agilebits.onepassword", @"de.petermaurer.TransientPasteboardType", @"com.typeit4me.clipping"]];
        for (NSString *type in types) {
            if ([secret containsObject:type]) {
                out[@"skip"] = @YES;
                return strdup(json_string(out).UTF8String);
            }
        }
        NSArray<NSURL *> *urls = [pb readObjectsForClasses:@[NSURL.class] options:@{NSPasteboardURLReadingFileURLsOnlyKey: @YES}];
        if (urls.count) {
            NSMutableArray *paths = [NSMutableArray array];
            for (NSURL *url in urls) {
                if (url.path) {
                    [paths addObject:url.path];
                }
            }
            out[@"files"] = paths;
        } else if ([types containsObject:NSPasteboardTypePNG] || [types containsObject:NSPasteboardTypeTIFF]) {
            NSData *data = [pb dataForType:NSPasteboardTypePNG];
            NSBitmapImageRep *rep = nil;
            if (!data) {
                NSData *tiff = [pb dataForType:NSPasteboardTypeTIFF];
                rep = tiff ? [NSBitmapImageRep imageRepWithData:tiff] : nil;
                data = [rep representationUsingType:NSBitmapImageFileTypePNG properties:@{}];
            } else {
                rep = [NSBitmapImageRep imageRepWithData:data];
            }
            if (data && image_out && [data writeToFile:@(image_out) atomically:YES]) {
                out[@"image"] = @YES;
                out[@"w"] = @(rep.pixelsWide);
                out[@"h"] = @(rep.pixelsHigh);
            }
        }
        NSString *text = [pb stringForType:NSPasteboardTypeString];
        if (text.length && !out[@"files"]) {
            out[@"text"] = text;
        }
        return strdup(json_string(out).UTF8String);
    }
}

// The app in front: "name\tbundle path" (malloc'd), or NULL.
char *nf_front_app(void) {
    @autoreleasepool {
        NSRunningApplication *front = NSWorkspace.sharedWorkspace.frontmostApplication;
        if (!front.localizedName) {
            return NULL;
        }
        return strdup([NSString stringWithFormat:@"%@\t%@", front.localizedName, front.bundleURL.path ?: @""].UTF8String);
    }
}

// Whether this app may send keys to others (Accessibility); with
// `prompt`, macOS asks to let it (once: after that, System Settings).
bool nf_accessibility(bool prompt) {
    NSDictionary *options = @{(__bridge id)kAXTrustedCheckOptionPrompt: @(prompt)};
    return AXIsProcessTrustedWithOptions((__bridge CFDictionaryRef)options);
}

// ⌘V to the app in front, as clipboard managers send it: a V with ⌘ set
// on it alone, into the session (no modifier key is pressed or held).
// ⌘C, to the app in front: what's selected there copied (for the text
// selected in an app that doesn't say what it is).
void nf_post_copy(void) {
    CGEventSourceRef source = CGEventSourceCreate(kCGEventSourceStateCombinedSessionState);
    CGEventRef down = CGEventCreateKeyboardEvent(source, 8, true);
    CGEventRef up = CGEventCreateKeyboardEvent(source, 8, false);
    CGEventSetFlags(down, kCGEventFlagMaskCommand);
    CGEventSetFlags(up, kCGEventFlagMaskCommand);
    CGEventPost(kCGSessionEventTap, down);
    CGEventPost(kCGSessionEventTap, up);
    CFRelease(down);
    CFRelease(up);
    if (source) CFRelease(source);
}

// The clipboard's change count: whether something's been copied since.
long nf_pasteboard_changes(void) {
    return NSPasteboard.generalPasteboard.changeCount;
}

// Whether ⌘, ⇧, ⌥ or ⌃ is held down now.
bool nf_modifiers_held(void) {
    CGEventFlags flags = CGEventSourceFlagsState(kCGEventSourceStateHIDSystemState);
    return (flags & (kCGEventFlagMaskCommand | kCGEventFlagMaskShift | kCGEventFlagMaskAlternate | kCGEventFlagMaskControl)) != 0;
}

void nf_post_paste(void) {
    CGEventSourceRef source = CGEventSourceCreate(kCGEventSourceStateCombinedSessionState);
    CGKeyCode v = 9;
    CGEventRef down = CGEventCreateKeyboardEvent(source, v, true);
    CGEventRef up = CGEventCreateKeyboardEvent(source, v, false);
    CGEventSetFlags(down, kCGEventFlagMaskCommand);
    CGEventSetFlags(up, kCGEventFlagMaskCommand);
    CGEventPost(kCGSessionEventTap, down);
    CGEventPost(kCGSessionEventTap, up);
    CFRelease(down);
    CFRelease(up);
    if (source) {
        CFRelease(source);
    }
}
